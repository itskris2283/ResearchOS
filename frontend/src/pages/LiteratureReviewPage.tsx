import { useState } from "react";
import { motion } from "framer-motion";
import {
  Download,
  RefreshCw,
  BookOpen,
  ChevronDown,
  ChevronRight,
  ExternalLink,
  Sparkles,
  Loader2,
} from "lucide-react";
import { Button } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { Separator } from "@/components/ui/separator";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import { useLiteratureReview, useGenerateReview } from "@/hooks/useLiteratureReview";
import { useWorkspace } from "@/contexts/WorkspaceContext";
import { toast } from "sonner";

export default function LiteratureReviewPage() {
  const [expandedSection, setExpandedSection] = useState<string | null>(null);
  const [exportFormat, setExportFormat] = useState<string>("markdown");
  const { currentWorkspace } = useWorkspace();
  const workspaceId = currentWorkspace?._id ?? "";
  const { data, isLoading } = useLiteratureReview(workspaceId);
  const generateReview = useGenerateReview();
  const review = data?.data;
  const sections = review?.sections ?? [];

  const handleGenerate = async () => {
    if (!workspaceId) return;
    try {
      await generateReview.mutateAsync(workspaceId);
      toast.success("Review generated!");
    } catch {
      toast.error("Failed to generate review");
    }
  };

  const handleExport = () => {
    if (!sections.length) {
      toast.error("No review to export");
      return;
    }
    
    let content = "# Literature Review\n\n";
    sections.forEach(s => {
      content += `## ${s.title}\n\n${s.content}\n\n`;
      if (s.citations && s.citations.length > 0) {
        content += `**Citations:** ${s.citations.join(", ")}\n\n`;
      }
    });

    const blob = new Blob([content], { type: "text/markdown" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `literature-review-${workspaceId}.md`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
    
    if (exportFormat === "pdf") {
        toast.info("PDF export is currently simulated by downloading markdown.");
    }
  };

  return (
    <div className="space-y-6">
      <div className="flex items-center justify-between">
        <div>
          <h1 className="text-2xl font-bold">Literature Review</h1>
          <p className="text-sm text-muted-foreground mt-1">
            AI-generated, citation-grounded literature review
          </p>
        </div>
        <div className="flex items-center gap-2">
          <Select value={exportFormat} onValueChange={setExportFormat}>
            <SelectTrigger className="w-[130px] h-9"><SelectValue placeholder="Format" /></SelectTrigger>
            <SelectContent>
              <SelectItem value="markdown">Markdown</SelectItem>
              <SelectItem value="pdf">PDF</SelectItem>
            </SelectContent>
          </Select>
          <Button variant="outline" size="sm" onClick={handleExport} disabled={!sections.length}>
            <Download className="h-4 w-4 mr-2" /> Export
          </Button>
          <Button variant="outline" size="sm" onClick={handleGenerate} disabled={generateReview.isPending || !workspaceId}>
            {generateReview.isPending ? <Loader2 className="h-4 w-4 mr-2 animate-spin" /> : <RefreshCw className="h-4 w-4 mr-2" />}
            Generate
          </Button>
        </div>
      </div>

      {!workspaceId ? (
        <div className="text-center py-16 text-muted-foreground">
          <BookOpen className="mx-auto h-10 w-10 mb-3 opacity-30" />
          <p className="text-sm">Select a workspace to view the literature review</p>
        </div>
      ) : isLoading ? (
        <div className="flex items-center justify-center py-16"><Loader2 className="h-8 w-8 animate-spin text-muted-foreground" /></div>
      ) : sections.length === 0 ? (
        <div className="text-center py-16 text-muted-foreground">
          <Sparkles className="mx-auto h-10 w-10 mb-3 opacity-30" />
          <p className="text-sm">No literature review yet</p>
          <p className="text-xs mt-1">Click "Generate" to create an AI-powered literature review</p>
        </div>
      ) : (
        <Card className="glass-card">
          <CardContent className="p-6">
            <div className="mb-6">
              <div className="flex items-center gap-2 mb-1">
                <BookOpen className="h-5 w-5 text-primary" />
                <h2 className="text-xl font-bold">Literature Review</h2>
              </div>
              <p className="text-sm text-muted-foreground">
                Generated by ResearchOS AI &bull; {sections.length} sections
              </p>
            </div>
            <Separator className="mb-6" />
            <div className="space-y-1">
              {sections.map((section) => (
                <div key={section.title} className="border rounded-lg overflow-hidden">
                  <button
                    onClick={() => setExpandedSection(expandedSection === section.title ? null : section.title)}
                    className="flex w-full items-center justify-between p-4 hover:bg-accent/50 transition-colors"
                  >
                    <span className="font-medium text-sm">{section.title}</span>
                    {expandedSection === section.title ? <ChevronDown className="h-4 w-4 text-muted-foreground" /> : <ChevronRight className="h-4 w-4 text-muted-foreground" />}
                  </button>
                  {expandedSection === section.title && (
                    <motion.div initial={{ height: 0, opacity: 0 }} animate={{ height: "auto", opacity: 1 }} className="px-4 pb-4">
                      <p className="text-sm text-muted-foreground leading-relaxed">{section.content}</p>
                      {section.citations?.length > 0 && (
                        <div className="mt-3 flex flex-wrap gap-1.5">
                          {section.citations.map((cit) => <Badge key={cit} variant="secondary" className="text-xs cursor-pointer"><ExternalLink className="h-3 w-3 mr-1" />{cit}</Badge>)}
                        </div>
                      )}
                    </motion.div>
                  )}
                </div>
              ))}
            </div>
          </CardContent>
        </Card>
      )}
    </div>
  );
}
